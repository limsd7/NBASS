export const getCombinedStressAdvice = (careType: string, subjectId: string): string[] => {
  const isAnxious = [CareType.ANXIETY_TENSION, CareType.HYPERSENSITIVE].includes(careType as CareType);
  const isExhausted = [CareType.BURNOUT, CareType.LOW_ENERGY, CareType.ADRENAL].includes(careType as CareType);
  
  const advices: string[] = [];

  if (subjectId === 'math') {
    if (isAnxious) {
      advices.push('💡 [수학 × 불안형] 계산 실수에 대한 두려움이 큽니다. 검산은 모의고사 전체를 다 푼 뒤에 한 번만 하는 규칙을 세워 불안감을 통제하세요.');
    }
    if (isExhausted) {
      advices.push('💡 [수학 × 무기력형] 킬러 문항을 보면 압도당해 무기력해질 수 있습니다. 이번 주는 2점, 3점짜리 쉬운 문제만 모아서 빠르게 풀며 성취감부터 회복하세요.');
    }
  }

  if (subjectId === 'korean') {
    if (isAnxious) {
      advices.push('💡 [국어 × 불안형] 첫 교시의 긴장감과 긴 지문이 불안을 극대화합니다. 지문을 읽기 전 깊은 심호흡을 3번 하고, "어차피 답은 지문 안에 있다"고 되뇌이세요.');
    }
    if (isExhausted) {
      advices.push('💡 [국어 × 무기력형] 글씨가 튕겨 나가는 현상(난독)이 올 수 있습니다. 하루에 긴 지문 1개만이라도 온전히 분석하는 데 만족하고 휴식을 취하세요.');
    }
  }

  if (subjectId === 'english') {
    if (isExhausted) {
      advices.push('💡 [영어 × 번아웃형] 듣기 평가나 쉬운 독해 위주로 가볍게 귀와 눈만 열어두는 감각 유지 위주의 학습을 권장합니다.');
    }
  }

  // 기본 폴백
  if (advices.length === 0) {
    advices.push('💡 현재 상태에서는 본인의 신체적/심리적 에너지를 먼저 회복한 뒤, 해당 과목의 기본기 위주로 가볍게 접근하는 것이 가장 중요합니다.');
    advices.push('💡 진단받은 신체 상태에 맞게 학습 시간을 무리하게 늘리지 말고, 휴식과 수면의 질을 높이는 데 투자하세요.');
  }

  return advices;
};

