      advices.push('📐 [수학 × 주의집중형] 풀이 공간이 어지러우면 부호 실수가 3배 증가합니다. 시험지 여백을 세로선으로 2등분하여 번호순으로 차례대로 정갈하게 적는 훈련을 하세요.');
