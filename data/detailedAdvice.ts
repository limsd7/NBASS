import { CareType } from '../types';

const getBmiCategory = (bmi: number): 'underweight' | 'normal' | 'overweight' | 'obese' => {
    if (bmi < 18.5) return 'underweight';
    if (bmi < 23) return 'normal';
    if (bmi < 25) return 'overweight';
    return 'obese';
};

const generateBmiAdvice = (student: { bmi?: number, weight?: number, height?: number }, advice_obj: any): { title: string, advice: string, detail: string } => {
    const bmi = student.bmi || 0;
    const category = getBmiCategory(bmi);
    const advice = advice_obj[category];

    const weight = student.weight || 0;
    const height = (student.height || 0) / 100;
    
    let detail = "";
    if (height > 0) {
        const target_bmi = category === 'underweight' ? 18.5 : 22.9;
        const target_weight = (target_bmi * height * height).toFixed(1);
        const weight_diff = Math.abs(weight - parseFloat(target_weight)).toFixed(1);

        if (category === 'underweight') {
            detail = ` 현재 BMI는 ${bmi.toFixed(1)}로 저체중 상태입니다. 최소 ${weight_diff}kg 증량하여 정상 범위(BMI 18.5 이상)에 도달하는 것을 권장합니다. 체중 증량을 위해 건강한 지방과 단백질 섭취를 늘리세요.`;
        } else if (category === 'normal') {
            detail = ` 현재 BMI는 ${bmi.toFixed(1)}로 매우 이상적인 상태입니다. 현재 체중을 ±2kg 범위 내에서 유지하는 것이 가장 좋습니다.`;
        } else if (category === 'overweight' || category === 'obese') {
            const status = category === 'overweight' ? '과체중' : '비만';
            detail = ` 현재 BMI는 ${bmi.toFixed(1)}로 ${status} 상태입니다. 건강한 학습 컨디션을 위해 ${weight_diff}kg 감량하여 정상 범위(BMI 22.9 이하)에 도달하는 것을 권장합니다.`;
        }
    }
    
    return {
        title: advice.title,
        advice: advice.advice,
        detail: detail
    };
}

