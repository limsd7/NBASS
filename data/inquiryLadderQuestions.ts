export const LIGHT_STAGES: LadderStageLevel[] = ['A', 'B', 'C'];

/** 단원명/과목ID로 라이트 뱅크 조회 (없으면 null → 기존 6단계·AI 경로) */
export function getLightLadder(unitName: string, subjectId: string = ''): LadderQuestion[] | null {
    const norm = `${subjectId} ${unitName}`.toLowerCase();
    for (const unit of LIGHT_LADDER_UNITS) {
        if (norm.includes(unit.unitId.toLowerCase())) return LIGHT_LADDERS[unit.unitId] || null;
        if (unit.keywords.some(k => norm.includes(k.toLowerCase()))) return LIGHT_LADDERS[unit.unitId] || null;
    }
    return null;
}
