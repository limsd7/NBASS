// Function to add ANS study methods to a CareType
function addAnsStudyMethods(content, careTypeName, methods) {
    // Find the pattern: anxietyExplanation: `...`\n    },\n\n    [CareType.NEXT...
    // We need to add the new fields before the closing },

    const pattern = new RegExp(
        `(\\[CareType\\.${careTypeName}\\]:[\\s\\S]*?anxietyExplanation:\\s*\`[^\`]+\`)(\`\\s*\\n\\s*\\},)`,
        'g'
    );

    const replacement = `$1\`,

        // ANS(자율신경) 활성 상태에 따른 공부법
        ansStudyMethodGeneral: \`${methods.general}\`,

        ansStudyMethodMath: \`${methods.math}\`,

        ansStudyMethodKorean: \`${methods.korean}\`,

        ansStudyMethodEnglish: \`${methods.english}\`
    },`;

    return content.replace(pattern, replacement);
}

